public class HouseholdDetails {
    public static void main(String[] args) {
        // Number of family members: integer
        int familyMembers = 5;

        // Water consumed in litres: decimal value
        double waterConsumed = 245.75;

        // House number: integer
        int houseNumber = 123;

        // Water usage status: character
        char waterStatus = 'A'; // Example: 'A' for Active, 'I' for Inactive

        // Displaying all details
        System.out.println("Household Details:");
        System.out.println("Number of Family Members: " + familyMembers);
        System.out.println("Water Consumed (litres): " + waterConsumed);
        System.out.println("House Number: " + houseNumber);
        System.out.println("Water Usage Status: " + waterStatus);
    }
}

